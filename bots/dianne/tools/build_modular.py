"""Assemble editable Boston phase modules into a standalone submission."""

import argparse
import ast
import hashlib
from pathlib import Path

DEFAULT = Path(__file__).resolve().parents[1] / "modular"


def standalone_fragment(source, filename):
    """Shared module imports are supplied by earlier assembled fragments."""
    tree = ast.parse(source, filename=filename)
    removed = set()
    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and node.level:
            if node.level != 1 or node.module not in {"common", "preflop", "auction", "postflop"}:
                raise ValueError(f"Unsupported relative import in {filename}")
            removed.update(range(node.lineno - 1, node.end_lineno))
    return "\n".join(line for index, line in enumerate(source.splitlines()) if index not in removed)


def build(common, preflop, auction, postflop, dispatcher):
    parts = ["# Generated by bots/dianne/tools/build_modular.py. Edit the phase sources."]
    for name, filename in (("common", common), ("preflop", preflop), ("auction", auction),
                           ("postflop", postflop), ("dispatcher", dispatcher)):
        source = filename.read_text()
        if name in {"preflop", "auction", "postflop"}:
            functions = {node.name for node in ast.parse(source).body if isinstance(node, ast.FunctionDef)}
            if name + "_decision" not in functions:
                raise ValueError(f"{filename} must define {name}_decision(state, memory)")
        digest = hashlib.sha256(source.encode()).hexdigest()
        parts.append(f"# {name} source SHA256 {digest}\n" + standalone_fragment(source, str(filename)))
    combined = "\n\n\n".join(parts) + "\n"
    compile(combined, "agent.py", "exec")
    return combined


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for phase in ("common", "preflop", "auction", "postflop", "dispatcher"):
        parser.add_argument("--" + phase, type=Path, default=DEFAULT / (phase + ".py"))
    parser.add_argument("--output", type=Path, default=DEFAULT / "agent.py")
    args = parser.parse_args()
    generated = build(args.common, args.preflop, args.auction, args.postflop, args.dispatcher)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)
    print(args.output)
    print("SHA256 " + hashlib.sha256(generated.encode()).hexdigest())


if __name__ == "__main__":
    main()
